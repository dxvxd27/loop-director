// Builds cues.js from the voice cues in cues/ (WAV, any bit depth, mono or stereo).
// File names are the cue keys: intro, verse, verse2, prechorus, chorus, chorus2, bridge, interlude, instrumental,
// solo, turnaround, breakdown, tag, outro, ending, count1..count4.
// Each file is mixed to mono, resampled to 22.05 kHz, trimmed and normalized, so the cue starts exactly on the beat.
// Usage: node tools/build-cues.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, extname, basename, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_RATE = 22050;

function readWav(buf) {
  const dv = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);
  let p = 12, fmt = 1, ch = 1, rate = 44100, bits = 16, data = null;
  while (p + 8 <= dv.byteLength) {
    const id = buf.toString("ascii", p, p + 4); const sz = dv.getUint32(p + 4, true);
    if (id === "fmt ") {
      fmt = dv.getUint16(p + 8, true); ch = dv.getUint16(p + 10, true); rate = dv.getUint32(p + 12, true); bits = dv.getUint16(p + 22, true);
      if (fmt === 0xfffe && sz >= 40) fmt = dv.getUint16(p + 32, true);
    } else if (id === "data") { data = [p + 8, Math.min(sz, dv.byteLength - p - 8)]; break; }
    p += 8 + sz + (sz & 1);
  }
  if (!data) throw new Error("no data chunk");
  const bps = bits / 8, frames = Math.floor(data[1] / (bps * ch));
  const read = o =>
    fmt === 3 ? (bits === 32 ? dv.getFloat32(o, true) : dv.getFloat64(o, true))
    : bits === 16 ? dv.getInt16(o, true) / 32768
    : bits === 24 ? (dv.getUint8(o) | dv.getUint8(o + 1) << 8 | dv.getInt8(o + 2) << 16) / 8388608
    : bits === 32 ? dv.getInt32(o, true) / 2147483648
    : (dv.getUint8(o) - 128) / 128;
  const mono = new Float32Array(frames);
  for (let i = 0; i < frames; i++) { let s = 0; for (let k = 0; k < ch; k++) s += read(data[0] + (i * ch + k) * bps); mono[i] = s / ch; }
  return { mono, rate };
}
function resample(x, from, to) {
  if (from === to) return x;
  const ratio = from / to, n = Math.floor(x.length / ratio), out = new Float32Array(n), w = Math.max(1, Math.round(ratio));
  for (let i = 0; i < n; i++) {
    const c = i * ratio; let s = 0, m = 0;
    for (let k = 0; k < w; k++) {
      const pos = c + k - (w - 1) / 2, a = Math.floor(pos), f = pos - a;
      if (a < 0 || a + 1 >= x.length) continue;
      s += x[a] * (1 - f) + x[a + 1] * f; m++;
    }
    out[i] = m ? s / m : 0;
  }
  return out;
}
function encode(mono, rate) {
  let a = 0; while (a < mono.length && Math.abs(mono[a]) < 0.01) a++;
  let b = mono.length - 1; while (b > a && Math.abs(mono[b]) < 0.01) b--;
  if (a >= b) throw new Error("silent");
  a = Math.max(0, a - Math.floor(rate * 0.002)); b = Math.min(mono.length - 1, b + Math.floor(rate * 0.05));
  let peak = 0; for (let i = a; i <= b; i++) peak = Math.max(peak, Math.abs(mono[i]));
  const g = 0.95 / peak, n = b - a + 1, out = Buffer.alloc(44 + n * 2);
  out.write("RIFF", 0); out.writeUInt32LE(36 + n * 2, 4); out.write("WAVEfmt ", 8); out.writeUInt32LE(16, 16);
  out.writeUInt16LE(1, 20); out.writeUInt16LE(1, 22); out.writeUInt32LE(rate, 24); out.writeUInt32LE(rate * 2, 28);
  out.writeUInt16LE(2, 32); out.writeUInt16LE(16, 34); out.write("data", 36); out.writeUInt32LE(n * 2, 40);
  for (let i = 0; i < n; i++) {
    const fade = Math.min(1, (n - i) / (rate * 0.01)); // 10 ms fade-out so the cut never clicks
    out.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(mono[a + i] * g * fade * 32767))), 44 + i * 2);
  }
  return out;
}

const result = {};
for (const f of readdirSync(join(root, "cues")).sort()) {
  if (extname(f).toLowerCase() !== ".wav") continue;
  const key = basename(f, extname(f)).toLowerCase();
  const { mono, rate } = readWav(readFileSync(join(root, "cues", f)));
  result[key] = encode(resample(mono, rate, OUT_RATE), OUT_RATE).toString("base64");
}
writeFileSync(join(root, "cues.js"),
  "// Generated by tools/build-cues.mjs from the files in cues/. Do not edit by hand.\nwindow.BUILTIN_CUES = " + JSON.stringify(result) + ";\n");
console.log("cues.js:", Object.keys(result).length, "cues");
